// Regenerate answers.js from an answer-key JSON: node tools/build-answers.mjs path/to/dap_an.json
// JSON shape: { data: [{ id, question, answer, verified }] }
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("Usage: node tools/build-answers.mjs <dap_an.json>");
  process.exit(1);
}
const { data } = JSON.parse(readFileSync(src, "utf8"));
if (!Array.isArray(data) || !data.every((x) => x.question && x.answer)) {
  console.error("Invalid file: expected { data: [{ question, answer, ... }] }");
  process.exit(1);
}
const rows = data.map(({ id, question, answer, verified }) => ({ id, question, answer, verified: !!verified }));
const out = new URL("../answers.js", import.meta.url);
writeFileSync(out, "// Generated by tools/build-answers.mjs\nvar ANSWERS = " + JSON.stringify(rows, null, 1) + ";\n");
console.log(`answers.js: ${rows.length} câu`);
